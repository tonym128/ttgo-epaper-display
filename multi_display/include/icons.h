// Returns matching 32x32 icon pointer for WMO Weather Code
inline const unsigned char* getWeatherIcon(int wmoCode, bool isDay = true) {
    switch (wmoCode) {
        case 0: // Clear sky
            return isDay ? icon_sun_32x32 : icon_moon_32x32;
        case 1: // Mainly clear
        case 2: // Partly cloudy
            return icon_partly_cloudy_32x32;
        case 3: // Overcast
            return icon_cloudy_32x32;
        case 45: // Fog
        case 48: // Depositing rime fog
            return icon_fog_32x32;
        case 51: case 53: case 55: // Drizzle
        case 61: case 63: case 65: // Rain
        case 80: case 81: case 82: // Rain showers
            return icon_rain_32x32;
        case 71: case 73: case 75: // Snow fall
        case 77: // Snow grains
        case 85: case 86: // Snow showers
            return icon_snow_32x32;
        case 95: // Thunderstorm
        case 96: case 99: // Thunderstorm with hail
            return icon_thunder_32x32;
        default:
            return icon_partly_cloudy_32x32;
    }
}

// Returns short textual description of WMO code
inline const char* getWeatherDescription(int wmoCode) {
    switch (wmoCode) {
        case 0:  return "Clear Sky";
        case 1:  return "Mainly Clear";
        case 2:  return "Partly Cloudy";
        case 3:  return "Overcast";
        case 45: return "Fog";
        case 48: return "Rime Fog";
        case 51: return "Light Drizzle";
        case 53: return "Drizzle";
        case 55: return "Dense Drizzle";
        case 61: return "Slight Rain";
        case 63: return "Moderate Rain";
        case 65: return "Heavy Rain";
        case 71: return "Slight Snow";
        case 73: return "Moderate Snow";
        case 75: return "Heavy Snow";
        case 77: return "Snow Grains";
        case 80: return "Slight Showers";
        case 81: return "Moderate Showers";
        case 82: return "Violent Showers";
        case 85: return "Snow Showers";
        case 86: return "Heavy Snow Showers";
        case 95: return "Thunderstorm";
        case 96: return "Thunder + Hail";
        case 99: return "Severe Thunder";
        default: return "Cloudy";
    }
}
